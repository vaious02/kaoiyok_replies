-- 1) ตารางแอดมิน ---------------------------------------------------------
create table if not exists public.admins (
  email      text primary key,
  note       text,
  created_at timestamptz not null default now()
);

-- ⬇️ เปลี่ยนเป็นอีเมลที่จะใช้ล็อกอิน ต้องตรงกับ user ที่สร้างใน Authentication → Users
insert into public.admins (email, note)
values ('admin@kaoiyok.com', 'เจ้าของศูนย์')
on conflict (email) do nothing;

-- 2) ตารางคำตอบ ----------------------------------------------------------
create table if not exists public.snippets (
  id         uuid primary key default gen_random_uuid(),
  category   text not null default 'ทั่วไป',
  title      text not null,
  situation  text,
  bubbles    text[] not null,
  note       text,
  sort_order int  not null default 0,
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists snippets_order_idx on public.snippets (sort_order, created_at);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists snippets_touch on public.snippets;
create trigger snippets_touch before update on public.snippets
for each row execute function public.touch_updated_at();

-- 3) ฟังก์ชันเช็คสิทธิ์ ----------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

grant execute on function public.is_admin() to anon, authenticated;

-- 4) สิทธิ์การเข้าถึง (RLS) ------------------------------------------------
alter table public.snippets enable row level security;
alter table public.admins   enable row level security;

-- ใครก็อ่านคำตอบที่เปิดใช้งานได้ (แอดมินหน้าเพจไม่ต้องล็อกอินก็ก๊อปได้)
drop policy if exists snippets_read on public.snippets;
create policy snippets_read on public.snippets
for select using (is_active or public.is_admin());

-- เพิ่ม แก้ ลบ เฉพาะแอดมิน
drop policy if exists snippets_insert on public.snippets;
create policy snippets_insert on public.snippets
for insert to authenticated with check (public.is_admin());

drop policy if exists snippets_update on public.snippets;
create policy snippets_update on public.snippets
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists snippets_delete on public.snippets;
create policy snippets_delete on public.snippets
for delete to authenticated using (public.is_admin());

-- ตาราง admins ไม่เปิดให้อ่านจากฝั่งเว็บเลย แก้ผ่าน SQL Editor เท่านั้น
drop policy if exists admins_none on public.admins;
create policy admins_none on public.admins for select using (false);

